#!/usr/bin/env node
// scripts/gen-llms-txt.mjs — writes llms.txt from the repo's own derived facts.
//
// llms.txt (https://llmstxt.org) is the entry point an agent reads instead of a 500-line
// README. Everything in it is DERIVED — skill names and one-liners from each SKILL.md's
// frontmatter, the endpoint count and the free/paid split from the generated catalog and
// `_lib/endpoint-owners.yaml`, the version from VERSION. Nothing is hand-listed, so it
// cannot drift the way a hand-written index does.
//
//   Regenerate:  node scripts/gen-llms-txt.mjs
//   Verify:      node --test tests/contracts/llms-txt.test.mjs
//
// tests/contracts/llms-txt.test.mjs re-runs this and fails on any difference, so a new
// skill or a repriced endpoint fails the build until llms.txt is regenerated.

import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import YAML from 'yaml';
import { spendSplit } from '../_lib/spend-split.mjs';

export const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const read = (rel) => readFileSync(join(ROOT, rel), 'utf8');

// Every number comes from the tree. The free/paid split is imported from
// tests/helpers/spend-split.mjs — the one implementation the README guard also uses, so
// llms.txt cannot disagree with the README about which skills spend money.
function facts () {
  const catalog = JSON.parse(read('_lib/api-catalog.json'));
  const { free } = spendSplit();
  const isFree = new Set(free);

  const dir = join(ROOT, 'skills');
  const skills = readdirSync(dir).filter((f) => statSync(join(dir, f)).isDirectory()).sort()
    .map((name) => {
      const body = read(join('skills', name, 'SKILL.md'));
      const fm = YAML.parse(/^---\n([\s\S]*?)\n---/.exec(body)[1]);
      // First sentence of the frontmatter description: the whole thing is a routing
      // trigger for the agent and runs long.
      const desc = String(fm.description ?? '').replace(/\s+/g, ' ').trim();
      const first = /^(.*?[.?!])(\s|$)/.exec(desc)?.[1] ?? desc;
      return { name, free: isFree.has(name), desc: first };
    });

  return {
    version: read('VERSION').trim(),
    endpoints: Object.keys(catalog.endpoints).length,
    skills,
    free: free.length
  };
}

export function render () {
  const f = facts();
  const line = (s) => `- [/${s.name}](skills/${s.name}/SKILL.md)${s.free ? ' (free)' : ''}: ${s.desc}`;

  return `# RichAPI GTM Skills

> ${f.skills.length} go-to-market skills for B2B outbound, over a runtime that prices every paid API call and refuses to make one until a human approves the total. Version ${f.version}.

This file is generated by \`scripts/gen-llms-txt.mjs\` from the repository's own derived
facts. Do not edit it by hand.

## What an agent needs to know first

- The runtime wraps ${f.endpoints} RichAPI endpoints. Pricing comes from the generated
  catalog \`_lib/api-catalog.json\`, never from a number written in prose.
- **No skill makes a paid call before a human approves a priced plan.** \`--dry-run\`
  prices a whole run and makes zero API calls. A declined plan exits 7, not 0.
- ${f.free} of the ${f.skills.length} skills never make a paid call at all, marked \`(free)\` below. They work
  against a checkout with no API key.
- Contact data lives in \`gtm/\`, which is gitignored, TTL-swept and erasable via
  \`/comply\`. Never commit it.
- Every threshold the runtime enforces is in one file, \`_lib/gates.yaml\`. A missing key
  fails closed rather than defaulting.
- This pack **exports**; it does not send, dial, or write into a CRM. See ROADMAP.md.

## Start here

- [README](README.md): what it is, the full skill table, and how finished it is.
- [Install](docs/INSTALL.md): the CLI and the skills install separately; both are needed.
- [Getting started](docs/GETTING-STARTED.md): first run, end to end.
- [Skill shape](docs/skill-shape.md): the contract every SKILL.md is validated against.

## Read before pointing this at money

- [LIMITATIONS.md](LIMITATIONS.md): what it cannot do or cannot verify, measured.
- [SECURITY.md](SECURITY.md): threat model, the narrowed tool grants, and the hole they do not close.
- [ROADMAP.md](ROADMAP.md): what is built, what is next, and what it will deliberately never do.

## Skills

${f.skills.map(line).join('\n')}

## Optional

- [CONTRIBUTING.md](CONTRIBUTING.md): setup, checks, and the seven laws every change is held to.
- [CHANGELOG.md](CHANGELOG.md): alphas can break; read between them.
- [docs/validation.md](docs/validation.md): what has been run against the live API.
- [docs/metrics.md](docs/metrics.md): what the pack measures about itself.
- [docs/TROUBLESHOOTING.md](docs/TROUBLESHOOTING.md): exit codes and what they mean.
`;
}

const OUT = join(ROOT, 'llms.txt');
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(OUT, render());
  console.log(`wrote llms.txt (${render().split('\n').length} lines)`);
}
